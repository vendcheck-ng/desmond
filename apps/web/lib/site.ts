/**
 * Single source of truth for the site's identity and its public URL.
 * Everything SEO-related (canonicals, sitemap, robots, Open Graph, JSON-LD, llms.txt)
 * imports from here so they can never disagree with each other.
 */

export const SITE_NAME = "Desmond Odeyemi";
export const DEFAULT_TITLE = "Desmond Odeyemi — Product Engineer & Product Designer";

/** Entity-rich on purpose: who, what, where. Used when no SEO description is set in the admin. */
export const DEFAULT_DESCRIPTION =
  "Desmond Odeyemi is a product engineer and designer based in Lagos, Nigeria. He designs and builds web and mobile products, and founded VendCheck.";

/** Pure so it can be unit-tested. Accepts "example.com", "https://example.com/", etc. */
export function normalizeSiteUrl(explicit?: string, vercelProductionHost?: string): string {
  const raw = explicit?.trim() || (vercelProductionHost?.trim() ? `https://${vercelProductionHost.trim()}` : "") || "http://localhost:3000";
  const withProtocol = /^https?:\/\//i.test(raw) ? raw : `https://${raw}`;
  return withProtocol.replace(/\/+$/, "");
}

export const SITE_URL = normalizeSiteUrl(process.env.NEXT_PUBLIC_SITE_URL, process.env.VERCEL_PROJECT_PRODUCTION_URL);
export const IS_LOCAL_URL = /^https?:\/\/(localhost|127\.0\.0\.1)(:|\/|$)/i.test(SITE_URL);

if (process.env.NODE_ENV === "production" && IS_LOCAL_URL) {
  // Loud, because a localhost canonical/sitemap quietly removes the site from search results.
  console.warn("[seo] NEXT_PUBLIC_SITE_URL is not set: canonicals, sitemap and social cards will point at localhost.");
}

export const absoluteUrl = (path = "/") => `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;

/** Branded default share card, generated by app/opengraph-image.tsx. */
export const OG_DEFAULT = {
  url: absoluteUrl("/opengraph-image"),
  width: 1200,
  height: 630,
  alt: DEFAULT_TITLE,
};
